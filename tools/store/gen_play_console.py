    a("")
    a("## 6. AdMob")
    a("")
    a(f"- Crie o app no AdMob (Android, `{pub['package_name']}`) e 3 blocos: banner, intersticial e premiado.")
    a(f"- ID do editor para o `app-ads.txt`: `{pub['admob']['publisher_id']}`.")
