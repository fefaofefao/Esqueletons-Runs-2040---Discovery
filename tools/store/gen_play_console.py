    a("| Medo / horror | Não (esqueletos são fofos e fazem aniversário) |")
    a("| Sexualidade / nudez | Não |")
    a("| Linguagem imprópria | Não |")
    a("| Drogas, álcool, tabaco | Não |")
    a("| Apostas / jogos de azar simulados | Não (não há compra de itens aleatórios nem caixas de recompensa) |")
