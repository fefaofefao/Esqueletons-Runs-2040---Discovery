def cell_from_block(block):
    """Converte um bloco de 9 linhas numa célula de 12 linhas."""
    w = len(block[0])
    cell = ["." * w for _ in range(LINE_H)]
    for i, row in enumerate(block):
        cell[BLOCK_TOP + i] = row
    return cell


def overlay(cell, rows, top):
    w = len(cell[0])
    mw = len(rows[0])
    # recorta/centraliza a marca na largura do glifo
    off = (w - mw) // 2
    out = list(cell)
    for i, mrow in enumerate(rows):
        line = list(out[top + i])
        for x, ch in enumerate(mrow):
            tx = x + off
            if ch == "#" and 0 <= tx < w:
                line[tx] = "#"
        out[top + i] = "".join(line)
    return out


def strip_i_dot(cell):
    out = list(cell)
    out[BLOCK_TOP] = "." * len(out[0])
    return out


def build_glyphs():
    glyphs = {}
    for table in (U, L, D, P):
        for ch, block in table.items():
            glyphs[ch] = cell_from_block(block)
    for ch, (base, mark) in COMPOSE.items():
        cell = glyphs[base]
        if base.islower():
            if base == "i":
                cell = strip_i_dot(cell)
            # acento ocupa as linhas 2-3 (acima da altura-x)
            cell = overlay(cell, ACC[mark], BLOCK_TOP)
        else:
            cell = overlay(cell, ACC[mark], 0)
        glyphs[ch] = cell
    # Cedilhas
    c_up = list(glyphs["C"])
    c_up = overlay(c_up, ["..#..", ".#..."], BLOCK_TOP + 7)
    glyphs["Ç"] = c_up
    c_lo = list(glyphs["c"])
    c_lo = overlay(c_lo, ["..#.", ".#.."], BLOCK_TOP + 7)
    glyphs["ç"] = c_lo
    return glyphs


def main():
    glyphs = build_glyphs()
    chars = sorted(glyphs.keys(), key=ord)
    cols = 16
    cell_w = 8
    rows = (len(chars) + cols - 1) // cols
    W = cols * (cell_w + 1)
    H = rows * (LINE_H + 1)
    # textura potência de 2
    tw, th = 1, 1
    while tw < W:
        tw *= 2
    while th < H:
        th *= 2
    img = Image.new("RGBA", (tw, th), (0, 0, 0, 0))
    px = img.load()
    lines = []
    for idx, ch in enumerate(chars):
        cell = glyphs[ch]
        w = len(cell[0])
        cx = (idx % cols) * (cell_w + 1)
        cy = (idx // cols) * (LINE_H + 1)
        for y, row in enumerate(cell):
            for x, c in enumerate(row):
                if c == "#":
                    px[cx + x, cy + y] = (255, 255, 255, 255)
        adv = w + 1
        lines.append(
            f"char id={ord(ch)} x={cx} y={cy} width={w} height={LINE_H} "
            f"xoffset=0 yoffset=0 xadvance={adv} page=0 chnl=15"
        )
    OUT.mkdir(parents=True, exist_ok=True)
    img.save(OUT / "pixel.png")
    header = [
        'info face="OssosPixel" size=12 bold=0 italic=0 charset="" unicode=1 '
        "stretchH=100 smooth=0 aa=1 padding=0,0,0,0 spacing=1,1 outline=0",
        f"common lineHeight={LINE_H} base={BASE} scaleW={tw} scaleH={th} pages=1 packed=0",
        'page id=0 file="pixel.png"',
        f"chars count={len(chars)}",
    ]
    (OUT / "pixel.fnt").write_text("\n".join(header + lines + ["kernings count=0"]) + "\n", encoding="utf-8")
    print(f"fonte: {len(chars)} glifos -> {OUT / 'pixel.fnt'}")


if __name__ == "__main__":
    main()
